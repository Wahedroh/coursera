import { expect, test } from '@playwright/test'

// รันท้ายสุด (เพิ่มคนเข้าห้องแล้วจำนวนนักเรียนของเทสต์อื่นจะเปลี่ยน)
test('ครูเพิ่มนักเรียนรายคน แล้วนักเรียนคนใหม่ตั้ง PIN และเข้าระบบได้', async ({ browser }) => {
  const t = await (await browser.newContext()).newPage()
  await t.goto('/teacher/login')
  await t.getByLabel('รหัสผ่านครู').fill('teacher-pass')
  await t.getByRole('button', { name: 'เข้าสู่ระบบ' }).click()
  await t.getByRole('link', { name: /โรงเรียนทดสอบ ชั้น 1/ }).click()
  await t.getByRole('button', { name: '+ เพิ่มนักเรียน' }).click()
  await t.getByLabel('ZipGrade ID').fill('3')
  await t.getByLabel('ชื่อ', { exact: true }).fill('ซ้ำ')
  await t.getByRole('button', { name: 'เพิ่ม', exact: true }).click()
  await expect(t.getByText(/ZipGrade ID 3 เป็นของ มานี มีนา/)).toBeVisible()
  await t.getByLabel('ZipGrade ID').fill('88')
  await t.getByLabel('คำนำหน้า').selectOption('เด็กหญิง')
  await t.getByLabel('ชื่อ', { exact: true }).fill('ใหม่ใจ')
  await t.getByLabel('นามสกุล').fill('ย้ายมา')
  await t.getByRole('button', { name: 'เพิ่ม', exact: true }).click()
  await expect(t.getByText('เพิ่ม เด็กหญิงใหม่ใจ ย้ายมา แล้ว', { exact: false })).toBeVisible()
  await expect(t.getByRole('cell', { name: 'เด็กหญิงใหม่ใจ ย้ายมา' })).toBeVisible()

  const s = await (await browser.newContext()).newPage()
  await s.goto('/')
  await s.getByLabel('รหัสนักเรียน (ZipGrade ID)').fill('88')
  await s.getByRole('button', { name: 'ถัดไป' }).click()
  await expect(s.getByText('ใหม่ใจ ย้ายมา', { exact: false })).toBeVisible()
})

test('หน้าแรกครูมีเมนูห้องเรียนครบ เลือกห้องแล้วไปหน้าของห้องนั้น และจำห้องที่เลือกไว้', async ({ page }) => {
  await page.goto('/teacher/login')
  await page.getByLabel('รหัสผ่านครู').fill('teacher-pass')
  await page.getByRole('button', { name: 'เข้าสู่ระบบ' }).click()
  await expect(page.getByRole('heading', { name: 'เมนูห้องเรียน' })).toBeVisible()
  for (const name of ['ตารางทวงงาน', '+ สร้างงาน', 'เช็กชื่อ', 'ผังห้อง & แต้ม', 'คะแนนสอบ', 'เกรด', 'คลิปย้อนหลัง', 'ประกาศ', 'เอกสารเรียน', 'ค่าเอกสาร'])
    await expect(page.getByRole('link', { name, exact: true })).toBeVisible()
  await page.getByLabel('เลือกห้องสำหรับเมนู').selectOption({ label: 'โรงเรียนทดสอบ ชั้น 1' })
  await page.getByRole('link', { name: 'ประกาศ', exact: true }).click()
  await expect(page.getByRole('link', { name: '← โรงเรียนทดสอบ ชั้น 1' })).toBeVisible()
  await page.getByRole('link', { name: 'หน้าแรก' }).click()
  await expect(page.getByLabel('เลือกห้องสำหรับเมนู')).toHaveValue(await page.getByLabel('เลือกห้องสำหรับเมนู').inputValue())
  await expect(page.getByLabel('เลือกห้องสำหรับเมนู').locator('option:checked')).toHaveText('โรงเรียนทดสอบ ชั้น 1')
})

test('หน้าห้อง: เห็นคะแนนนักเรียน เรียงมาก→น้อย/น้อย→มาก ดูรายชิ้น และลบนักเรียนได้', async ({ page }) => {
  await page.goto('/teacher/login')
  await page.getByLabel('รหัสผ่านครู').fill('teacher-pass')
  await page.getByRole('button', { name: 'เข้าสู่ระบบ' }).click()
  await page.getByRole('link', { name: /โรงเรียนทดสอบ ชั้น 1/ }).click()
  const totals = async () => {
    await expect(page.getByRole('button', { name: /^ดูคะแนน / }).first()).toBeVisible()
    return (await page.getByRole('button', { name: /^ดูคะแนน / }).allTextContents()).map(Number)
  }
  await page.getByLabel('เรียงตาม').selectOption('desc')
  const desc = await totals()
  expect(desc.length).toBeGreaterThan(1)
  expect(desc).toEqual([...desc].sort((a, b) => b - a))
  await page.getByLabel('เรียงตาม').selectOption('asc')
  const asc = await totals()
  expect(asc).toEqual([...asc].sort((a, b) => a - b))

  await page.getByRole('button', { name: 'ดูคะแนน มานี มีนา' }).click()
  await expect(page.getByText(/^งาน \(\d+\)$/)).toBeVisible()
  await expect(page.getByText(/^คะแนนสอบ \(\d+\)$/)).toBeVisible()

  // ลบนักเรียนที่เพิ่มในเทสต์ก่อนหน้า (รหัส 88)
  page.once('dialog', (d) => d.accept())
  const row = page.getByRole('row', { name: /เด็กหญิงใหม่ใจ ย้ายมา/ })
  await row.getByRole('button', { name: 'ลบ', exact: true }).click()
  await expect(page.getByText('ลบ เด็กหญิงใหม่ใจ ย้ายมา แล้ว')).toBeVisible()
  await expect(page.getByRole('row', { name: /ใหม่ใจ ย้ายมา/ })).toHaveCount(0)
  // นักเรียนที่ถูกลบเข้าระบบไม่ได้อีก
  const s = await (await page.context().browser()!.newContext()).newPage()
  await s.goto('/')
  await s.getByLabel('รหัสนักเรียน (ZipGrade ID)').fill('88')
  await s.getByRole('button', { name: 'ถัดไป' }).click()
  await expect(s.getByText(/ไม่พบรหัสนี้/)).toBeVisible()
})
